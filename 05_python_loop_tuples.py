# 1. Basic 'for' Loop Through a Tuple
# Iterating directly through the items of a tuple
thistuple = ("apple", "banana", "cherry")

print("--- Iterating Through Tuple Items ---")
for x in thistuple:
    print(x)

# Output:
# apple
# banana
# cherry

# ==========================================
# Key Takeaway:
# - A 'for' loop automatically iterates through each item in the tuple one by one.
# - Useful for processing, printing, or applying logic to tuple elements dynamically.
